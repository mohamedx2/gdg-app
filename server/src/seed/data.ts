const event = (
  partial: Omit<GdgEvent, 'coverImage'> & { coverSeed?: string },
): GdgEvent => {
  const { coverSeed, ...rest } = partial;
  return { ...rest, coverImage: cover(coverSeed ?? rest.id) };
};

